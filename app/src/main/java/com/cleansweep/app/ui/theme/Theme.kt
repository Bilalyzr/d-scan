/** Whether this theme draws in dark colours. A null theme, before the settings were read, follows the system. */
fun ThemeMode?.isDark(
    systemIsDark: Boolean,
): Boolean = when (this) {
    null, ThemeMode.SYSTEM -> systemIsDark
    ThemeMode.LIGHT -> false
    ThemeMode.DARK -> true
}

